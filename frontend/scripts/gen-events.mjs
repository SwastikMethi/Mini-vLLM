// Regenerates src/types/events.ts from the checked-in event contract.
// The contract encodes per-type payloads as allOf if/then branches, which
// json-schema-to-typescript ignores; rewrite them as a oneOf so the output
// is a union discriminated on `type`.
import { readFileSync, writeFileSync } from 'node:fs'
import { compile } from 'json-schema-to-typescript'

const src = new URL('../../mini_vllm_docs/contracts/event_schema.json', import.meta.url)
const out = new URL('../src/types/events.ts', import.meta.url)
const schema = JSON.parse(readFileSync(src, 'utf8'))

const pascal = (s) => s.split(/[._]/).map((w) => w[0].toUpperCase() + w.slice(1)).join('')
const { allOf, ...base } = schema

const variants = allOf.map((branch) => {
  const type = branch.if.properties.type.const
  const { payload, ...overrides } = branch.then.properties
  return {
    title: `${pascal(type)}Event`,
    type: 'object',
    properties: {
      ...base.properties,
      ...overrides,
      type: { const: type },
      payload: { ...payload, title: `${pascal(type)}Payload` },
    },
    required: base.required,
    additionalProperties: false,
  }
})

const ts = await compile(
  { title: 'EngineEvent', description: base.description, oneOf: variants },
  'EngineEvent',
  {
    bannerComment: '/* Generated by `npm run gen:events` from mini_vllm_docs/contracts/event_schema.json. Do not edit. */',
    additionalProperties: false,
    unreachableDefinitions: false,
    style: { semi: false, singleQuote: true },
  },
)
writeFileSync(out, ts + `\nexport type EventType = EngineEvent['type']\n`)
console.log(`wrote ${out.pathname}`)
